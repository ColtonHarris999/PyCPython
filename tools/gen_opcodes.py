"""Generate pycpython/opcodes.py from the CPython 3.14 source tree.

Usage: python tools/gen_opcodes.py /path/to/cpython > pycpython/opcodes.py

Sources read:
  Lib/_opcode_metadata.py                       opmap, HAVE_ARGUMENT, MIN_INSTRUMENTED_OPCODE
  Include/opcode.h                              NB_* binary-op opargs
  Include/internal/pycore_intrinsics.h          INTRINSIC_* ids
  Include/internal/pycore_opcode_metadata.h     num_popped/num_pushed, flags, caches, pseudo targets
  Include/internal/pycore_opcode_utils.h        MAKE_FUNCTION_*, RESUME_*
  Include/internal/pycore_code.h                COMPARISON_*
"""
import re
import sys
import os
import ast

root = sys.argv[1]


def read(p):
    with open(os.path.join(root, p), encoding="utf-8") as f:
        return f.read()


# --- opmap ---------------------------------------------------------------
md = read("Lib/_opcode_metadata.py")
ns = {}
tree = ast.parse(md)
for node in tree.body:
    if isinstance(node, ast.Assign):
        name = node.targets[0].id
        ns[name] = ast.literal_eval(node.value)
opmap = ns["opmap"]
specialized = ns["_specialized_opmap"]
HAVE_ARGUMENT = ns["HAVE_ARGUMENT"]
MIN_INSTRUMENTED_OPCODE = ns["MIN_INSTRUMENTED_OPCODE"]
allops = dict(opmap)
allops.update(specialized)

# --- NB_* ------------------------------------------------------------------
nb = re.findall(r"#define (NB_\w+)\s+(\d+)", read("Include/opcode.h"))
# --- intrinsics -------------------------------------------------------------
intr = re.findall(r"#define ((?:INTRINSIC|MAX_INTRINSIC)_\w+)\s+(\d+)",
                  read("Include/internal/pycore_intrinsics.h"))
# --- MAKE_FUNCTION / RESUME -------------------------------------------------
utils = read("Include/internal/pycore_opcode_utils.h")
mkf = re.findall(r"#define (MAKE_FUNCTION_\w+)\s+(0x[0-9a-fA-F]+)", utils)
resume = re.findall(r"#define (RESUME_\w+)\s+(\d+)", utils)
# --- COMPARISON_* ------------------------------------------------------------
code_h = read("Include/internal/pycore_code.h")
cmp = re.findall(r"#define (COMPARISON_(?:UNORDERED|LESS_THAN|GREATER_THAN|EQUALS))\s+(\d+)", code_h)

# --- metadata header ---------------------------------------------------------
meta = read("Include/internal/pycore_opcode_metadata.h")


def parse_switch(func_name):
    m = re.search(r"int %s\(int opcode, int oparg\)\s*\{\s*switch\(opcode\) \{(.*?)default:" % func_name,
                  meta, re.S)
    body = m.group(1)
    result = {}
    pending = []
    for line in body.splitlines():
        line = line.strip()
        if not line:
            continue
        mc = re.match(r"case (\w+):", line)
        if mc:
            pending.append(mc.group(1))
            continue
        mr = re.match(r"return (.*);", line)
        if mr:
            expr = mr.group(1).strip()
            for name in pending:
                result[name] = expr
            pending = []
    return result


popped = parse_switch("_PyOpcode_num_popped")
pushed = parse_switch("_PyOpcode_num_pushed")

flag_defs = dict((n, int(v)) for n, v in re.findall(r"#define (HAS_\w+_FLAG) \((\d+)\)", meta))
m = re.search(r"const struct opcode_metadata _PyOpcode_opcode_metadata\[\d+\] = \{(.*?)\};", meta, re.S)
flags = {}
for name, fmt, fl in re.findall(r"\[(\w+)\] = \{ true, ([-\w]+), ([^}]*?) \}", m.group(1)):
    val = 0
    for f in fl.split("|"):
        f = f.strip()
        if f and f != "0":
            val |= flag_defs[f]
    flags[name] = val

m = re.search(r"const uint8_t _PyOpcode_Caches\[256\] = \{(.*?)\};", meta, re.S)
caches = dict((n, int(v)) for n, v in re.findall(r"\[(\w+)\] = (\d+)", m.group(1)))

m = re.search(r"const struct pseudo_targets _PyOpcode_PseudoTargets\[\d+\] = \{(.*?)\};", meta, re.S)
pseudo_targets = {}
for name, as_seq, targets in re.findall(r"\[(\w+)-256\] = \{ (\d), \{ ([^}]*) \} \}", m.group(1)):
    tl = [t.strip() for t in targets.split(",")]
    tl = [t for t in tl if t != "0"]
    pseudo_targets[name] = (int(as_seq), tl)

m = re.search(r"const uint8_t _PyOpcode_Deopt\[256\] = \{(.*?)\};", meta, re.S)
deopt = {}
for a, b in re.findall(r"\[(\w+)\] = (\w+)", m.group(1)):
    deopt[a] = b


def c_expr_to_py(expr):
    # expressions are simple arithmetic over `oparg`
    e = expr.replace("&&", " and ").replace("||", " or ")
    return e


out = []
w = out.append
w('"""Opcode metadata for CPython 3.14 (generated by tools/gen_opcodes.py; do not edit)."""')
w("")
w("HAVE_ARGUMENT = %d" % HAVE_ARGUMENT)
w("MIN_INSTRUMENTED_OPCODE = %d" % MIN_INSTRUMENTED_OPCODE)
w("MAX_REAL_OPCODE = 254")
w("MIN_PSEUDO_OPCODE = 256")
w("MAX_PSEUDO_OPCODE = %d" % max(opmap.values()))
w("")
w("opmap = {")
for k, v in sorted(opmap.items(), key=lambda kv: kv[1]):
    w("    %r: %d," % (k, v))
w("}")
w("")
w("opname = {v: k for k, v in opmap.items()}")
w("")
for k, v in sorted(opmap.items(), key=lambda kv: kv[1]):
    w("%s = %d" % (k, v))
w("")
for n, v in nb:
    w("%s = %s" % (n, v))
w("")
for n, v in intr:
    w("%s = %s" % (n, v))
w("")
for n, v in mkf:
    w("%s = %s" % (n, v))
for n, v in resume:
    w("%s = %s" % (n, v))
w("")
for n, v in cmp:
    w("%s = %s" % (n, v))
w("COMPARISON_NOT_EQUALS = COMPARISON_UNORDERED | COMPARISON_LESS_THAN | COMPARISON_GREATER_THAN")
w("")
for n, v in sorted(flag_defs.items(), key=lambda kv: kv[1]):
    w("%s = %d" % (n, v))
w("")
w("# flags indexed by opcode (real + pseudo)")
w("_flags = {")
for name, val in sorted(flags.items(), key=lambda kv: allops.get(kv[0], 999)):
    if name in opmap:
        w("    %s: %d," % (name, val))
w("}")
w("")
w("_caches = {")
for name, val in caches.items():
    w("    %s: %d," % (name, val))
w("}")
w("")
w("_pseudo_targets = {")
for name, (as_seq, tl) in pseudo_targets.items():
    w("    %s: (%d, (%s)), " % (name, as_seq, ", ".join(tl) + ("," if len(tl) == 1 else "")))
w("}")
w("")
w("_popped = {")
for name, expr in popped.items():
    if name in opmap:
        w("    %s: lambda oparg: %s," % (name, c_expr_to_py(expr)))
w("}")
w("")
w("_pushed = {")
for name, expr in pushed.items():
    if name in opmap:
        w("    %s: lambda oparg: %s," % (name, c_expr_to_py(expr)))
w("}")
w("")
w('''

def num_popped(opcode, oparg):
    f = _popped.get(opcode)
    if f is None:
        return -1
    return f(oparg)


def num_pushed(opcode, oparg):
    f = _pushed.get(opcode)
    if f is None:
        return -1
    return f(oparg)


def flags(opcode):
    return _flags.get(opcode, 0)


def has_arg(opcode):
    return bool(_flags.get(opcode, 0) & HAS_ARG_FLAG)


def has_const(opcode):
    return bool(_flags.get(opcode, 0) & HAS_CONST_FLAG)


def has_name(opcode):
    return bool(_flags.get(opcode, 0) & HAS_NAME_FLAG)


def has_jump(opcode):
    return bool(_flags.get(opcode, 0) & HAS_JUMP_FLAG)


def has_free(opcode):
    return bool(_flags.get(opcode, 0) & HAS_FREE_FLAG)


def has_local(opcode):
    return bool(_flags.get(opcode, 0) & HAS_LOCAL_FLAG)


def caches(opcode):
    return _caches.get(opcode, 0)


def is_pseudo_instr(opcode):
    return MIN_PSEUDO_OPCODE <= opcode <= MAX_PSEUDO_OPCODE


def is_valid_opcode(opcode):
    return (0 <= opcode <= MAX_REAL_OPCODE and opcode in opname) or is_pseudo_instr(opcode)


def is_pseudo_target(pseudo, target):
    ent = _pseudo_targets.get(pseudo)
    if ent is None:
        return False
    return target in ent[1]


def is_block_push_opcode(opcode):
    return opcode in (SETUP_FINALLY, SETUP_WITH, SETUP_CLEANUP)


def has_target(opcode):
    return has_jump(opcode) or is_block_push_opcode(opcode)


def is_scope_exit_opcode(opcode):
    return opcode in (RETURN_VALUE, RAISE_VARARGS, RERAISE)


def is_terminator_opcode(opcode):
    return has_jump(opcode) or is_scope_exit_opcode(opcode)


def is_assembler_opcode(opcode):
    return opcode in (JUMP_FORWARD, JUMP_BACKWARD, JUMP_BACKWARD_NO_INTERRUPT)


def is_backwards_jump_opcode(opcode):
    return opcode in (JUMP_BACKWARD, JUMP_BACKWARD_NO_INTERRUPT)


def is_unconditional_jump_opcode(opcode):
    return opcode in (JUMP, JUMP_NO_INTERRUPT, JUMP_FORWARD, JUMP_BACKWARD,
                      JUMP_BACKWARD_NO_INTERRUPT)


def is_conditional_jump_opcode(opcode):
    return opcode in (POP_JUMP_IF_FALSE, POP_JUMP_IF_TRUE, POP_JUMP_IF_NONE,
                      POP_JUMP_IF_NOT_NONE)


def is_return_opcode(opcode):
    return opcode == RETURN_VALUE


def is_raise_opcode(opcode):
    return opcode in (RAISE_VARARGS, RERAISE)
''')
print("\n".join(out))
