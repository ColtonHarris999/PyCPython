"""Generate pycpython/pyast.py from CPython's Parser/Python.asdl.

Tooling only (not part of the shipped library's runtime path).

Usage: python tools/gen_ast.py /path/to/cpython/Parser/Python.asdl > pycpython/pyast.py
"""
import re
import sys

BUILTIN_TYPES = {'identifier', 'int', 'string', 'constant'}


def parse_asdl(text):
    # strip comments
    text = re.sub(r'--[^\n]*', '', text)
    m = re.search(r'module\s+\w+\s*\{(.*)\}', text, re.S)
    body = m.group(1)
    # split into definitions "name = ..."
    defs = re.split(r'\n\s*(?=[a-z_]+\s*=)', body)
    result = []
    for d in defs:
        d = d.strip()
        if not d:
            continue
        name, rhs = d.split('=', 1)
        name = name.strip()
        attributes = []
        am = re.search(r'attributes\s*\(([^)]*)\)', rhs)
        if am:
            attributes = parse_fields(am.group(1))
            rhs = rhs[:am.start()] + rhs[am.end():]
        rhs = rhs.strip()
        if rhs.startswith('('):
            # product type
            fields = parse_fields(rhs[1:rhs.index(')')])
            result.append(('product', name, fields, attributes))
        else:
            constructors = []
            for alt in rhs.split('|'):
                alt = alt.strip()
                cm = re.match(r'(\w+)\s*(?:\(([^)]*)\))?', alt)
                cname = cm.group(1)
                fields = parse_fields(cm.group(2)) if cm.group(2) else []
                constructors.append((cname, fields))
            result.append(('sum', name, constructors, attributes))
    return result


def parse_fields(s):
    fields = []
    for part in s.split(','):
        part = part.strip()
        if not part:
            continue
        m = re.match(r'(\w+)([*?]*)\s+(\w+)', part)
        typ, quals, fname = m.groups()
        fields.append((typ, quals, fname))
    return fields


HEADER = '''"""AST node classes mirroring CPython 3.14's ``ast`` module.

Generated by tools/gen_ast.py from Parser/Python.asdl.  DO NOT EDIT.

These classes deliberately mimic the public shape of ``ast.AST`` nodes
(``_fields``, ``_attributes``, positional/keyword construction) so that the
test harness can convert them 1:1 into real ``ast`` nodes.  The shipped
library never imports the stdlib ``ast`` module.
"""


class AST:
    _fields = ()
    _attributes = ()
    _field_types = {}

    def __init__(self, *args, **kwargs):
        names = self._fields + self._attributes
        if len(args) > len(names):
            raise TypeError("%s constructor takes at most %d positional argument%s"
                            % (type(self).__name__, len(names),
                               "" if len(names) == 1 else "s"))
        d = self.__dict__
        for name, value in zip(names, args):
            if value is None and name in self._list_fields:
                value = []
            d[name] = value
        for name, value in kwargs.items():
            if value is None and name in self._list_fields:
                value = []
            d[name] = value
        for name in names[len(args):]:
            if name not in kwargs:
                if name in self._list_fields:
                    d[name] = []
                else:
                    d[name] = None

    _defaults = {}
    _list_fields = frozenset()

    def __repr__(self):
        d = self.__dict__
        return "%s(%s)" % (type(self).__name__,
                           ", ".join("%s=%r" % (f, d.get(f)) for f in self._fields))


class expr_context(AST):
    pass


class boolop(AST):
    pass


class operator(AST):
    pass


class unaryop(AST):
    pass


class cmpop(AST):
    pass

'''


def main():
    with open(sys.argv[1]) as f:
        defs = parse_asdl(f.read())
    out = [HEADER]
    simple_sums = {}
    for kind, name, payload, attributes in defs:
        if kind == 'sum':
            constructors = payload
            if all(not fields for _, fields in constructors):
                # simple sum: singleton instances
                simple_sums[name] = [c for c, _ in constructors]
                continue
            out.append("class %s(AST):\n    _attributes = %r\n\n" % (name, tuple(a[2] for a in attributes)))
            for cname, fields in constructors:
                emit_class(out, cname, name, fields, attributes)
        else:
            fields = payload
            emit_class(out, name, 'AST', fields, attributes)
    for name, constructors in simple_sums.items():
        if name not in ('expr_context', 'boolop', 'operator', 'unaryop', 'cmpop'):
            out.append("class %s(AST):\n    pass\n\n\n" % name)
        for c in constructors:
            out.append("class %s(%s):\n    _fields = ()\n\n\n" % (c, name))
    # singleton instances for simple sums (CPython uses singletons)
    for name, constructors in simple_sums.items():
        for c in constructors:
            out.append("%s_singleton = %s()\n" % (c, c))
    out.append("\n")
    print("".join(out).rstrip() + "\n")


def emit_class(out, cname, base, fields, attributes):
    fnames = tuple(f[2] for f in fields)
    lst = [f[2] for f in fields if '*' in f[1]]
    out.append("class %s(%s):\n" % (cname, base))
    out.append("    _fields = %r\n" % (fnames,))
    out.append("    _attributes = %r\n" % (tuple(a[2] for a in attributes),))
    out.append("    _list_fields = frozenset(%r)\n" % (lst,))
    out.append("    _field_types = %r\n" % ({f[2]: f[0] + f[1] for f in fields},))
    out.append("\n\n")


if __name__ == '__main__':
    main()
